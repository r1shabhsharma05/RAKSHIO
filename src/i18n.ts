// When the fraud happened, in the UI language. The stored display string
// ('kal, 7 baje') is Hinglish by construction, so hg keeps it verbatim;
// en/hi are rebuilt from the stored Date (today / yesterday / day before,
// else a short date) so no Hinglish leaks into an English script or draft.
// No Date and no display → null, and the caller skips the sentence.
export function whenText(fraudAt: Date | string | null, display: string | null, lang: Lang): string | null {
  if (lang === 'hg') return display;
  const d = fraudAt ? new Date(fraudAt) : null;
  if (!d || Number.isNaN(d.getTime())) return display;
  const now = new Date();
  const startOf = (x: Date) => new Date(x.getFullYear(), x.getMonth(), x.getDate()).getTime();
  const dayDiff = Math.round((startOf(now) - startOf(d)) / 86400000);
  const hour24 = d.getHours();
  const hour12 = hour24 % 12 === 0 ? 12 : hour24 % 12;
  if (lang === 'en') {
    const day = dayDiff === 0 ? 'today' : dayDiff === 1 ? 'yesterday' : dayDiff === 2 ? 'the day before yesterday' : d.toLocaleDateString('en-IN', { day: 'numeric', month: 'short' });
    return `${day} at ${hour12} ${hour24 < 12 ? 'AM' : 'PM'}`;
  }
  const period = hour24 >= 5 && hour24 < 12 ? 'सुबह' : hour24 >= 12 && hour24 < 17 ? 'दोपहर' : hour24 >= 17 && hour24 < 21 ? 'शाम' : 'रात';
  const day = dayDiff === 0 ? 'आज' : dayDiff === 1 ? 'कल' : dayDiff === 2 ? 'परसों' : d.toLocaleDateString('hi-IN', { day: 'numeric', month: 'short' });
  return `${day} ${period} ${hour12} बजे`;
}
